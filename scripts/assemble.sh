#!/usr/bin/env bash
# Collect per-runner reports into reports/<YYYY-MM>/, reports/latest/,
# append to reports/history.tsv and regenerate README.md.
# Usage: scripts/assemble.sh <dir-with-report-and-summary-files>
set -euo pipefail

src="${1:-artifacts}"
month="$(date -u +%Y-%m)"
dest="reports/${month}"

mkdir -p "$dest" reports/latest
rm -f reports/latest/*
find "$src" -type f \( -name 'report-*.md' -o -name 'summary-*.tsv' \) -exec cp {} "$dest"/ \;
cp "$dest"/* reports/latest/

hist=reports/history.tsv
first=$(ls "$dest"/summary-*.tsv | head -1)
if [ ! -f "$hist" ]; then head -1 "$first" > "$hist"; fi
for f in "$dest"/summary-*.tsv; do tail -n +2 "$f" >> "$hist"; done
# a re-run on the same day replaces that day's row for the runner
tac "$hist" | awk -F'\t' '!seen[$1 FS $2]++' | tac > "${hist}.tmp" && mv "${hist}.tmp" "$hist"

# tsv -> markdown table (selected columns by name)
tsv_md() {
  awk -F'\t' -v cols="$2" '
    BEGIN { n = split(cols, want, ",") }
    NR == 1 { for (i = 1; i <= NF; i++) idx[$i] = i
              line = "|"; sep = "|"
              for (j = 1; j <= n; j++) { line = line " " want[j] " |"; sep = sep "---|" }
              print line; print sep; next }
    { line = "|"; for (j = 1; j <= n; j++) line = line " " $(idx[want[j]]) " |"; print line }
  ' "$1"
}

latest_cols="label,macos,R,sf,gdal_sf,gdal_terra,gdal_gdalraster,gdal_vapour,proj_sf,geos_sf,n_drivers,recipe_gdal,recipe_proj,recipe_geos"
hist_cols="date,label,gdal_sf,gdal_terra,gdal_gdalraster,gdal_vapour,proj_sf,geos_sf,n_drivers,recipe_gdal"

{
  cat <<'EOF'
# gdalosx

What GDAL (and PROJ, GEOS) do the CRAN macOS binary packages actually carry?

A GitHub Actions workflow runs on the first of each month (and on demand) on
macOS runners, installs the CRAN binaries of sf, terra, gdalraster and vapour,
and records:

* the GDAL / PROJ / GEOS versions each package binary is linked against
  (each binary bundles its own static copy, so they can differ)
* the registered GDAL drivers, with a key-driver table across packages
* round-trip probes for common raster and vector formats, and /vsicurl/ reads
* PROJ data paths, network setting and a basic transform check
* the newest library tarballs published at mac.r-project.org for CRAN's builders

Reports are committed to `reports/<YYYY-MM>/`, the most recent run is mirrored
in `reports/latest/`, and one line per runner per run goes in
`reports/history.tsv`.

<!-- this file is regenerated by scripts/assemble.sh; edit that instead -->

EOF
  echo "## Latest (${month})"
  echo
  # combine summaries for a single table
  tmp=$(mktemp)
  head -1 "$first" > "$tmp"
  for f in "$dest"/summary-*.tsv; do tail -n +2 "$f" >> "$tmp"; done
  tsv_md "$tmp" "$latest_cols"
  rm -f "$tmp"
  echo
  echo "Full reports:"
  echo
  for f in "$dest"/report-*.md; do
    b=$(basename "$f")
    echo "* [${b%.md}](reports/latest/${b})"
  done
  echo
  echo "## History (most recent 24 rows)"
  echo
  { head -1 "$hist"; tail -n +2 "$hist" | tail -n 24 | sort -r; } > "${hist}.tmp"
  tsv_md "${hist}.tmp" "$hist_cols"
  rm -f "${hist}.tmp"
} > README.md
